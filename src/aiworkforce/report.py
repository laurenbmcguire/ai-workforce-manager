"""Markdown report and JSON summary writers."""

from __future__ import annotations

import json
from pathlib import Path

import pandas as pd

from .policy import STRATEGY_LABELS


def md_table(df: pd.DataFrame, cols: list[str], headers: list[str] | None = None,
             fmt: dict | None = None) -> str:
    fmt = fmt or {}
    headers = headers or cols
    lines = ["| " + " | ".join(headers) + " |", "|" + "|".join(["---"] * len(cols)) + "|"]
    for _, r in df.iterrows():
        cells = [fmt[c](r[c]) if c in fmt else str(r[c]) for c in cols]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines)


def pct(v) -> str:
    return f"{100 * float(v):.1f}%"


def usd(v) -> str:
    v = float(v)
    return f"-${abs(v):,.0f}" if v < 0 else f"${v:,.0f}"


def usd2(v) -> str:
    return f"${float(v):,.2f}"


STRATEGY_COLS = ["strategy", "cost_per_task", "first_pass_quality", "sla_attainment",
                 "escalation_rate", "human_review_hours", "incidents", "incident_rate",
                 "value_delivered", "net_value", "reviewer_utilization"]
STRATEGY_HEADERS = ["Strategy", "Cost / task", "First-pass quality", "SLA attainment",
                    "Escalation rate", "Review hours", "Incidents", "Incident rate",
                    "Value delivered", "Net value", "Reviewer utilization"]


def strategy_markdown(table: pd.DataFrame) -> str:
    t = table.copy()
    t["strategy"] = t["strategy"].map(STRATEGY_LABELS)
    return md_table(t, STRATEGY_COLS, STRATEGY_HEADERS, {
        "cost_per_task": usd2, "first_pass_quality": pct, "sla_attainment": pct,
        "escalation_rate": pct, "incident_rate": pct, "value_delivered": usd,
        "net_value": usd, "reviewer_utilization": pct,
        "human_review_hours": lambda v: f"{float(v):,.0f}"})


def agent_markdown(akpi: pd.DataFrame) -> str:
    cols = ["name", "role", "model_tier", "autonomy", "tasks", "throughput_per_week",
            "first_pass_quality", "escalation_rate", "human_review_hours", "cost_per_task",
            "sla_attainment", "incident_rate", "value_delivered"]
    headers = ["Agent", "Role", "Tier", "Autonomy", "Tasks", "Tasks / week", "First-pass quality",
               "Escalation", "Review h", "Cost / task", "SLA", "Incident rate", "Value delivered"]
    return md_table(akpi, cols, headers, {
        "autonomy": lambda v: f"L{int(v)}", "first_pass_quality": pct, "escalation_rate": pct,
        "sla_attainment": pct, "incident_rate": pct, "cost_per_task": usd2,
        "value_delivered": usd, "human_review_hours": lambda v: f"{float(v):.1f}"})


def write_report(path: Path, summary: dict, table: pd.DataFrame, akpi: pd.DataFrame,
                 raci_md: str) -> None:
    dep = summary["deployed_strategy"]
    ov = summary["overall"]
    cap = summary["capacity_plan"]
    lines = [
        "# AI Workforce Report",
        "",
        "Generated by `python -m aiworkforce run` on **synthetic data** (seeded generator, "
        f"{summary['data']['tasks']:,} tasks over {summary['data']['weeks']} weeks, "
        f"{summary['data']['agents']} AI agents, {summary['data']['supervisors']} human supervisors). "
        "No real people, systems or business results are represented.",
        "",
        "## Headline",
        "",
        f"- Deployed routing strategy: **{STRATEGY_LABELS[dep]}** (highest net value of the three).",
        f"- First-pass quality {pct(ov['first_pass_quality'])}, SLA attainment "
        f"{pct(ov['sla_attainment'])}, incident rate {pct(ov['incident_rate'])}, "
        f"fully loaded cost {usd2(ov['cost_per_task'])} per task.",
        f"- Human oversight: {ov['human_review_hours']:,.0f} reviewer hours over the period "
        f"({pct(ov['reviewer_utilization'])} of supervisor capacity).",
        f"- Next month needs **{cap['hours_needed']:.0f} supervisor hours** vs "
        f"{cap['hours_available']:.0f} available. {cap['recommendation']}.",
        "",
        "## Routing strategy comparison",
        "",
        "All three strategies run on the same task stream with the same random draws "
        "(common random numbers), so differences come from routing alone.",
        "",
        strategy_markdown(table),
        "",
        "![Strategy comparison](../docs/img/strategy_comparison.png)",
        "",
        f"## Agent KPIs ({STRATEGY_LABELS[dep]})",
        "",
        agent_markdown(akpi),
        "",
        "![Agent scorecard](../docs/img/agent_scorecard.png)",
        "",
        "## Performance reviews",
        "",
        "| Agent | Recommendation | Evidence |",
        "|---|---|---|",
    ]
    for rv in summary["performance_reviews"]:
        lines.append(f"| {rv['name']} | **{rv['action']}** | " + "; ".join(rv["evidence"]) + " |")
    lines += [
        "",
        "## RACI matrix (humans x AI agents x task types)",
        "",
        raci_md,
        "## Capacity plan: supervisor hours next month",
        "",
        f"- Volume trend: {cap['trend_tasks_per_day_per_day']:+.3f} tasks/day per day; forecast "
        f"{cap['forecast_tasks']:,} tasks over the next {cap['horizon_business_days']} business days "
        f"({cap['forecast_tasks_per_day']} per day).",
        f"- Observed human effort: {cap['human_minutes_per_task']} min per task "
        f"(approvals, rework, escalations, audit samples), plus a {cap['buffer']:.0%} buffer.",
        f"- Hours needed: **{cap['hours_needed']:.1f}**; available: {cap['hours_available']:.1f} "
        f"({pct(cap['planned_utilization'])} planned utilization).",
        f"- If the autonomy recommendations are applied: {cap['hours_needed_after_recommendations']:.1f} h.",
        "",
        md_table(pd.DataFrame(cap["per_supervisor"]), ["supervisor", "needed_hours",
                 "available_hours", "utilization"], ["Supervisor", "Hours needed",
                 "Hours available", "Utilization"], {"utilization": pct}),
        "",
        "![Review load vs capacity](../docs/img/review_load.png)",
        "",
        "## Weekly throughput and incidents",
        "",
        "![Weekly throughput](../docs/img/weekly_throughput.png)",
        "",
        "## Audit log",
        "",
        f"Every routing, oversight and outcome decision is logged ({summary['audit']['events']:,} "
        f"events for the deployed strategy). Full log: `reports/audit_log.csv` (regenerated, not "
        f"committed); first 200 events: `reports/audit_log_sample.csv`.",
        "",
        "| Event | Count |",
        "|---|---|",
    ]
    for k, v in summary["audit"]["by_type"].items():
        lines.append(f"| {k} | {v:,} |")
    lines.append("")
    path.write_text("\n".join(lines), encoding="utf-8")


def write_summary(path: Path, summary: dict) -> None:
    path.write_text(json.dumps(summary, indent=2, default=float) + "\n", encoding="utf-8")
